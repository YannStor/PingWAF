/// A security event generated by the WAF engine.
///
/// Sent to the control plane for analysis and dashboard display.
#[derive(Debug, Clone)]
pub struct SecurityEvent {
    pub site_id: String,
    pub request_id: String,
    pub client_ip: String,
    pub method: String,
    pub scheme: String,
    pub protocol: String,
    pub host: String,
    pub path: String,
    pub query_string: String,
    pub rule_id: String,
    /// Identifier of the rule that actually enforced the action (L3-006);
    /// empty when the verdict came from the score gate, not a specific rule.
    pub enforced_rule_id: String,
    pub rule_name: String,
    /// Which protection produced the event: `managed` / `waf` / `ip_geo` /
    /// `bot` / `rate_limit` / `challenge`. Drives dashboard deep links.
    pub event_type: String,
    pub action: String,
    pub score: u32,
    pub details: String,
    /// Status code actually returned to the client for this event
    /// (403 for block, 503 for challenge, 0 when the request continues).
    pub response_status: u32,
    pub user_agent: String,
    pub country_code: String,
    pub matched_tags: Vec<String>,
}

