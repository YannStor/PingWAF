/// The PingWAF agent that connects to the control plane, caches rules locally,
/// and provides an API for pingap plugins to query WAF state.
///
/// # Usage
///
/// ```no_run
/// use pingwaf_agent::{PingWafAgent, config::AgentConfig};
///
/// # async fn example() -> anyhow::Result<()> {
/// // Start the agent (connects to control plane in background)
/// let agent = PingWafAgent::start(AgentConfig::default()).await?;
///
/// // Query rules for a domain
/// if let Some(rules) = agent.get_rules_for_domain("example.com") {
///     println!("WAF enabled: {:?}", rules.waf_config);
/// }
/// # Ok(())
/// # }
/// ```
pub struct PingWafAgent {
    pub config: AgentConfig,
    pub client: Arc<ControlPlaneClient>,
    pub rule_cache: Arc<RuleCache>,
    pub metrics: Arc<MetricsCollector>,
}

impl PingWafAgent {
    /// Initialize and start the agent.
    ///
    /// This connects to the control plane server in the background,
    /// registers the agent, and starts heartbeat/log-shipping tasks.
    /// If the server is unreachable, the agent operates from cached rules.
    pub async fn start(config: AgentConfig) -> anyhow::Result<Arc<Self>> {
        info!("Starting PingWAF agent...");

        let agent_id = config.resolved_agent_id();
        let cache_dir = std::path::PathBuf::from(&config.cache_dir);

        // Initialize rule cache (loads from disk if available)
        let rule_cache = RuleCache::new(cache_dir, agent_id.clone())?;

        // Initialize metrics collector
        let metrics = Arc::new(MetricsCollector::new());

        // Create the gRPC client
        let client = Arc::new(ControlPlaneClient::new(
            config.clone(),
            Arc::clone(&rule_cache),
            Arc::clone(&metrics),
        ));

        let agent = Arc::new(Self {
            config,
            client: Arc::clone(&client),
            rule_cache,
            metrics,
        });

        // Set as global instance
        AGENT_INSTANCE.store(Some(Arc::clone(&agent)));

        // Start background tasks (connection, heartbeat, log shipping)
        if let Err(e) = client.start().await {
            error!(error = %e, "Failed to start client background tasks");
            // Don't fail — agent can still operate from cached rules
        }

        info!(agent_id = %agent_id, "PingWAF agent started");
        Ok(agent)
    }

    /// Get the global agent instance (if started).
    pub fn instance() -> Option<Arc<Self>> {
        AGENT_INSTANCE.load_full()
    }

    /// Replace the global agent instance. Only compiled with the
    /// `test-util` feature: lets integration tests install an agent built
    /// without connecting to a control plane.
    #[cfg(feature = "test-util")]
    pub fn set_agent_instance(agent: Option<Arc<Self>>) {
        AGENT_INSTANCE.store(agent);
    }

    /// Get rules for a specific domain (used by WAF plugin on the hot path).
    ///
    /// Returns `None` if no rules are cached for this domain.
    #[inline]
    pub fn get_rules_for_domain(
        &self,
        domain: &str,
    ) -> Option<Arc<cache::SiteRules>> {
        self.rule_cache.get_site_rules(domain)
    }

    /// Get rules for a specific site by ID.
    #[inline]
    pub fn get_rules_for_site(
        &self,
        site_id: &str,
    ) -> Option<Arc<cache::SiteRules>> {
        self.rule_cache.get_site_rules_by_id(site_id)
    }

    /// Check if an IP is dynamically blocked for a site.
    #[inline]
    pub fn is_ip_blocked(&self, site_id: &str, ip: &str) -> bool {
        self.rule_cache.is_ip_blocked(site_id, ip)
    }

    /// The reason an IP is dynamically blocked for a site, or `None`.
    #[inline]
    pub fn blocked_reason(&self, site_id: &str, ip: &str) -> Option<String> {
        self.rule_cache.blocked_reason(site_id, ip)
    }

    /// When a dynamic block expires, wrapped in `Option` twice: the outer
    /// `None` means the IP is not blocked; the inner `None` means a
    /// permanent block. Used by the edge so refusal events can carry the
    /// unblocking time (L3-002).
    #[inline]
    pub fn blocked_expires_at(
        &self,
        site_id: &str,
        ip: &str,
    ) -> Option<Option<chrono::DateTime<chrono::Utc>>> {
        self.rule_cache.blocked_expires_at(site_id, ip)
    }

    /// Dynamically block an IP for a site. Called by the WAF plugin when a
    /// block verdict fires so the edge keeps refusing the client before the
    /// engine even runs; the block is reported to the control plane on the
    /// next heartbeat.
    #[inline]
    pub fn block_ip(
        &self,
        site_id: &str,
        ip: &str,
        duration: Option<std::time::Duration>,
        reason: &str,
    ) {
        self.rule_cache.block_ip(site_id, ip, duration, reason)
    }

    /// Log a security event (non-blocking, queued for batch shipping).
    pub fn log_security_event(&self, event: SecurityEvent) {
        let entry = client::LogEntry {
            site_id: event.site_id,
            request_id: event.request_id,
            client_ip: event.client_ip,
            method: event.method,
            scheme: event.scheme,
            host: event.host,
            path: event.path,
            query_string: event.query_string,
            protocol: event.protocol,
            request_headers: std::collections::HashMap::new(),
            request_body: None,
            request_body_size: 0,
            request_body_truncated: false,
            response_status: event.response_status,
            response_headers: std::collections::HashMap::new(),
            response_body: None,
            response_body_size: 0,
            response_body_truncated: false,
            upstream_addr: String::new(),
            upstream_latency_ms: 0,
            waf_score: event.score,
            waf_action: event.action,
            waf_rule_id: event.rule_id,
            waf_enforced_rule_id: event.enforced_rule_id,
            waf_rule_name: event.rule_name,
            waf_event_type: event.event_type,
            waf_details: event.details,
            waf_matched_tags: event.matched_tags,
            total_latency_ms: 0,
            cache_status: String::new(),
            tls_version: String::new(),
            ja3_hash: String::new(),
            country_code: event.country_code,
            city: String::new(),
            asn: 0,
            user_agent: event.user_agent,
            referer: String::new(),
        };
        self.client.send_log(entry);
    }

    /// Log an access entry (non-blocking, queued for batch shipping).
    pub fn log_access(&self, entry: AccessLogEntry) {
        let request_headers = combine_headers(entry.request_headers);
        let response_headers = combine_headers(entry.response_headers);
        let log_entry = client::LogEntry {
            site_id: entry.site_id,
            request_id: entry.request_id,
            client_ip: entry.client_ip,
            method: entry.method,
            scheme: entry.scheme,
            host: entry.host,
            path: entry.path,
            query_string: entry.query_string,
            protocol: entry.protocol,
            request_headers,
            request_body: entry.request_body,
            request_body_size: entry.request_body_size,
            request_body_truncated: entry.request_body_truncated,
            response_status: entry.status_code,
            response_headers,
            response_body: entry.response_body,
            response_body_size: entry.response_body_size,
            response_body_truncated: entry.response_body_truncated,
            upstream_addr: entry.upstream_addr,
            upstream_latency_ms: entry.upstream_latency_ms,
            waf_score: 0,
            waf_action: String::new(),
            waf_rule_id: String::new(),
            waf_enforced_rule_id: String::new(),
            waf_rule_name: String::new(),
            waf_event_type: String::new(),
            waf_details: String::new(),
            waf_matched_tags: Vec::new(),
            total_latency_ms: entry.total_latency_ms,
            cache_status: entry.cache_status,
            tls_version: entry.tls_version,
            ja3_hash: String::new(),
            country_code: entry.country_code,
            city: String::new(),
            asn: 0,
            user_agent: entry.user_agent,
            referer: entry.referer,
        };
        self.client.send_log(log_entry);
    }

    /// Record a request for metrics (hot path — must be fast).
    #[inline]
    pub fn record_request(&self, blocked: bool) {
        self.metrics.record_request(blocked);
    }

    /// Record a connection change (+1 on accept, -1 on close).
    #[inline]
    pub fn record_connection(&self, delta: i64) {
        self.metrics.record_connection(delta);
    }

    /// Check if the agent is connected to the control plane.
    #[inline]
    pub fn is_connected(&self) -> bool {
        self.client.is_connected()
    }

    /// Whether `domain` should keep being served while the control plane is
    /// unreachable and no synced rules exist for it.
    ///
    /// Resolution order: the site's own failover policy from the registry
    /// (primary or alternate domain match), then the control-plane-wide
    /// default from the last sync, then this agent's local `--fail-open`
    /// setting — which is the only layer available in standalone mode or
    /// before the first sync completes.
    pub fn effective_fail_open(&self, domain: &str) -> bool {
        match self.rule_cache.failover_for_domain(domain) {
            Some(cache::FailoverMode::Open) => return true,
            Some(cache::FailoverMode::Closed) => return false,
            Some(cache::FailoverMode::Inherit) | None => {},
        }
        self.rule_cache
            .global_fail_open()
            .unwrap_or(self.config.fail_open)
    }

    /// Get the current config hash (for delta sync). Cheap: clones the `Arc`,
    /// not the string.
    pub fn config_hash(&self) -> Arc<str> {
        self.rule_cache.config_hash()
    }

    /// Graceful shutdown — signals all background tasks to stop.
    pub async fn shutdown(&self) {
        info!("Shutting down PingWAF agent...");
        self.client.shutdown();

        // Persist cache one final time
        if let Err(e) = self.rule_cache.persist_to_disk() {
            error!(error = %e, "Failed to persist cache during shutdown");
        }

        // Clear global instance
        AGENT_INSTANCE.store(None);
        info!("PingWAF agent shut down complete");
    }
}

/// Combines repeated header names into the single value the wire format's
/// header map accepts.
///
/// `Set-Cookie` pairs are joined with a newline instead of the canonical
/// comma: cookie values routinely carry `Expires`/`Path` attributes that
/// contain commas of their own, so a comma join makes the pairs
/// indistinguishable (`a=1, b=2` reads as one cookie or two depending on
/// the attribute). Consumers split this header on `\n` and the rest on `, `.
fn combine_headers(
    headers: Vec<(String, String)>,
) -> std::collections::HashMap<String, String> {
    let mut map: std::collections::HashMap<String, String> =
        std::collections::HashMap::with_capacity(headers.len());
    for (name, value) in headers {
        match map.entry(name) {
            std::collections::hash_map::Entry::Occupied(mut existing) => {
                let separator =
                    if existing.key().eq_ignore_ascii_case("set-cookie") {
                        "\n"
                    } else {
                        ", "
                    };
                let combined = existing.get_mut();
                combined.reserve(value.len() + separator.len());
                combined.push_str(separator);
                combined.push_str(&value);
            },
            std::collections::hash_map::Entry::Vacant(slot) => {
                slot.insert(value);
            },
        }
    }
    map
}

/// Start the PingWAF agent with the given configuration.
///
/// Convenience function that calls [`PingWafAgent::start`].
pub async fn start_agent(
    config: AgentConfig,
) -> anyhow::Result<Arc<PingWafAgent>> {
    PingWafAgent::start(config).await
}

